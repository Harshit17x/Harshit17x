// Lay out a monogram as bitmap rows, each font pixel drawn `scale` cells wide, with one font pixel between letters.
export function monogramRows(text, scale = 1) {
  const glyphs = [...text.toUpperCase()].map((ch) => {
    const g = PIXEL_FONT[ch];
    if (!g) throw new Error(`no pixel glyph for ${JSON.stringify(ch)}`);
    return g;
  });
  const rows = [];
  for (let y = 0; y < 5; y++) {
    const line = glyphs.map((g) => g[y]).join('.');
    const wide = [...line].map((c) => c.repeat(scale)).join('');
    for (let k = 0; k < scale; k++) rows.push(wide);
  }
  return rows;
}
