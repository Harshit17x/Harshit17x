import { createHash } from 'node:crypto';
import { esc } from './svg.mjs';

// One <picture> that swaps dark/light SVGs with the viewer's theme. ?v= busts GitHub's image cache on change.
function picture(card, width) {
  const v = createHash('sha1').update(card.dark).update(card.light).digest('hex').slice(0, 10);
  const src = (mode) => `./generated/${card.name}-${mode}.svg?v=${v}`;
  const pic = `<picture><source media="(prefers-color-scheme: dark)" srcset="${src('dark')}"><source media="(prefers-color-scheme: light)" srcset="${src('light')}"><img src="${src('dark')}" width="${width}" alt="${esc(card.alt)}"></picture>`;
  return card.href ? `<a href="${esc(card.href)}">${pic}</a>` : pic;
}

// rows: arrays of cards sharing one line; each card takes an equal share of the width.
export function renderReadme(rows) {
  const lines = ['<!-- Generated by scripts/build.mjs. Edit profile.config.json, not this file. -->'];
  for (const row of rows) {
    const width = `${Math.floor(100 / row.length)}%`;
    lines.push(`<p align="center">${row.map((card) => picture(card, width)).join('')}</p>`);
  }
  return `${lines.join('\n\n')}\n`;
}
